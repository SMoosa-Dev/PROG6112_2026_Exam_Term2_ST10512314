private void processSale() {

    // Get customer information
    String customerName = CustomerNameTab.getText();
    String productName = ProductComboBox.getSelectedItem().toString();

    // Get product price
    double price;

    try {
        price = Double.parseDouble(PriceTab.getText());

        if (price <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Please enter a price greater than zero.");
            return;
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Please enter a valid product price.");
        return;
    }

    // Check customer name
    if (customerName.trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter the customer's name.");
        return;
    }

    // Create ProductCalculations object
    ProductCalculations calculations =
            new ProductCalculations(price);

    // Calculate VAT, Commission and Total
    double vat = calculations.GetVat();
    double commission = calculations.GetCommission();
    double total = calculations.GetTotal();

    // Display information
    InformationArea.setText(
            "Customer Name: " + customerName
            + "\nProduct: " + productName
            + "\nVAT: R " + vat
            + "\nCOMMISSION: R " + commission
            + "\nTOTAL: R " + total
    );

    // Save information to data.txt
    try {
        FileWriter writer = new FileWriter("data.txt", true);

        writer.write("DATA LOG\n");
        writer.write("************************************\n");
        writer.write("Customer Name: " + customerName + "\n");
        writer.write("Product: " + productName + "\n");
        writer.write("VAT: R " + vat + "\n");
        writer.write("COMMISSION: R " + commission + "\n");
        writer.write("TOTAL: R " + total + "\n");
        writer.write("************************************\n\n");

        writer.close();

        JOptionPane.showMessageDialog(this,
                "Sale processed and saved successfully!");

    } catch (IOException e) {
        JOptionPane.showMessageDialog(this,
                "Error saving information to file.");
    }
}


